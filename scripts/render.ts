import type { MethodDefinition } from "./method.ts";

/** Renders the route table, `MethodTypeMap` and the documented `Namespaces`. */
export function renderRoutesModule(definitions: readonly MethodDefinition[]): string {
	// An ID is a tag and an x-sdk-method, so it needs no escaping
	const routes = definitions.map(({ id, route }) => `\t"${id}": ${JSON.stringify(route)},`);
	const methodTypes = definitions.map(
		({ id, typePrefix }) =>
			`\t"${id}": MethodTypes<T.${typePrefix}Data, T.${typePrefix}Responses, (typeof routes)["${id}"]>;`,
	);
	const paginated = definitions.filter(({ route }) => route.pagination).map(({ id }) => `"${id}"`);
	const namespaces = [...Map.groupBy(definitions, ({ namespace }) => namespace)].map(([namespace, members]) => {
		const lines = members.map((definition) => {
			const type = definition.route.pagination ? "PaginatedMethod" : "Method";

			return indent(`${renderJsDoc(definition)}\n${definition.method}: ${type}<"${definition.id}">;`, "\t\t");
		});

		return `\t${namespace}: {\n${lines.join("\n")}\n\t};`;
	});

	return `// Generated by scripts/generate.ts from spec/openapi.yaml. Do not edit.
import type * as T from "./types.gen.ts";
import type { Route } from "../route.ts";
import type { MethodTypes, Method, PaginatedMethod } from "../types.ts";

/** Every method's route, by ID. \`as const\` keeps each route's literal types, which \`MethodTypes\` reads for the body, required params and pagination */
export const routes = {
${routes.join("\n")}
} as const;

// Checked apart from the declaration, as --isolatedDeclarations needs it to have no other type
routes satisfies Record<MethodId, Route>;

/** Each method's types, by ID, from hey-api's types for it and its route */
export interface MethodTypeMap {
${methodTypes.join("\n")}
}

/** Every method's ID, like \`task.get\` */
export type MethodId = keyof MethodTypeMap;

/** The IDs of paginated methods, the only ones \`pages()\` takes */
export type PaginatedMethodId = ${paginated.join(" | ") || "never"};

/**
 * Every endpoint, as \`clickup.<namespace>.<method>()\`, taking its params as ClickUp requires them.
 * \`WithWorkspace\` re-types them for a client with a workspace ID.
 */
export interface Namespaces {
${namespaces.join("\n")}
}
`;
}

/** Renders every code sample into a module, so tsc can check them. */
export function renderSamplesModule(definitions: readonly MethodDefinition[]): string {
	const samples = definitions.map(({ id, docs }) => `\t"${id}": async () => {\n${indent(docs.sample, "\t\t")}\n\t},`);

	return `// Generated by scripts/generate.ts from spec/openapi.yaml's x-codeSamples, so tsc checks them. Do not edit.
import { createClickUp } from "../index.ts";

/** A client as the docs recommend: with a workspace, which fills in \`team_id\` and \`workspace_id\` */
const clickup = createClickUp({ workspace: { id: 1234567 } });

export const samples: Record<string, () => Promise<void>> = {
${samples.join("\n")}
};
`;
}

/** Renders the method reference. */
export function renderApiPage(definitions: readonly MethodDefinition[]): string {
	const namespaces = Map.groupBy(
		definitions.toSorted((a, b) => a.id.localeCompare(b.id)),
		({ namespace }) => namespace,
	);
	const sections = [...namespaces].map(([namespace, members]) =>
		[`## ${namespace}`, ...members.map(renderApiSection)].join("\n\n"),
	);

	return `# API

Every endpoint is a method on the client, \`clickup.<namespace>.<method>(params, options)\`. The [client reference](./reference/index.md) covers \`createClickUp\`, its options, [\`pages()\`](./reference/index.md#pages) and the errors it throws.

${sections.join("\n\n")}
`;
}

/** Renders a generated method's JSDoc: its summary, description, endpoint, example and reference link. */
function renderJsDoc({ id, route, docs }: Pick<MethodDefinition, "id" | "route" | "docs">): string {
	const lines = [
		docs.summary,
		...(docs.description ? ["", ...docs.description.split("\n")] : []),
		"",
		`\`${route.method} ${route.path}\``,
		...(route.pagination ? ["", renderPagesNote(id, route.pagination.items)] : []),
		"",
		"@example",
		"```ts",
		...docs.sample.split("\n"),
		"```",
		`@see {@link ${docs.referenceUrl} | ClickUp reference}`,
	];
	const body = lines.map((line) => ` *${line && ` ${line}`}`).join("\n");

	return `/**\n${body}\n */`;
}

/** What a paginated method's docs say about its pages; `items` is the response field that holds them. */
function renderPagesNote(id: string, items: string): string {
	return `Each call returns one page of \`${items}\`; \`pages(clickup.${id}, params)\` reads every page.`;
}

/** One method's section of the API page. */
function renderApiSection({ id, route, docs }: Pick<MethodDefinition, "id" | "route" | "docs">): string {
	const rows = docs.params.map(
		(param) =>
			`| \`${param.name}\` | ${param.in} | \`${param.type}\` | ${param.required ? "yes" : ""} | ${param.description.replaceAll("|", "\\|").replaceAll("\n", "<br>")} |`,
	);

	return [
		`### ${id}`,
		`**${docs.summary}** · \`${route.method} ${route.path}\` · [ClickUp reference](${docs.referenceUrl})`,
		...(docs.description ? [docs.description] : []),
		`\`\`\`ts\n${docs.sample}\n\`\`\``,
		...(rows.length > 0
			? [`| Parameter | In | Type | Required | Description |\n| --- | --- | --- | --- | --- |\n${rows.join("\n")}`]
			: []),
		`Returns [\`Promise<Result<"${id}">>\`](./reference/index.md#result).${route.pagination ? ` ${renderPagesNote(id, route.pagination.items)}` : ""}`,
	].join("\n\n");
}

/** Indents non-blank lines. */
function indent(text: string, prefix: string): string {
	return text
		.split("\n")
		.map((line) => (line ? `${prefix}${line}` : line))
		.join("\n");
}
